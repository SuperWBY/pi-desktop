const assert = require('node:assert/strict')
const fs = require('node:fs')
const { randomUUID } = require('node:crypto')
const path = require('node:path')

module.exports = async function testDictation(page) {
  const input = page.locator('.composer-input')
  const mic = page.getByRole('button', { name: '语音输入', exact: true })
  const stop = page.getByRole('button', { name: '结束录音并转写', exact: true })
  const status = page.locator('.dictation-status')
  const bar = page.locator('.dictation-bar')
  const waveform = bar.locator('canvas')
  const cancel = bar.getByRole('button', { name: '取消录音', exact: true })
  const shots = path.resolve(__dirname, '../output/dictation')
  fs.mkdirSync(shots, { recursive: true })
  const start = async () => {
    await mic.click()
    await stop.waitFor()
    return await page.evaluate(() => window.dictationRequests.at(-1).id)
  }
  const emit = (event) => page.evaluate((value) => window.emitDictation(value), event)
  const waitValue = (text) => page.waitForFunction((value) => document.querySelector('.composer-input')?.value === value, text)

  await input.fill('请看占位部分。')
  await input.evaluate((node) => node.setSelectionRange(2, 4))
  const image = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jc9sAAAAASUVORK5CYII=', 'base64')
  await page.locator('.composer input[type="file"]').setInputFiles({ name: 'dictation.png', mimeType: 'image/png', buffer: image })
  await page.locator('.attachment').waitFor()
  await input.evaluate((node) => node.setSelectionRange(2, 4))
  const first = await start()
  assert.equal(await page.evaluate(() => window.dictationRequests.at(-1).locale), 'zh-CN')
  await bar.locator('.dictation-dot').waitFor()
  assert.equal(await bar.getByText('正在录音', { exact: true }).count(), 0)
  assert.equal(await bar.locator('.dictation-time').count(), 0)
  assert.equal(await bar.getByRole('status').textContent(), '麦克风已开启')
  assert.equal(await bar.locator('.dictation-announcement').evaluate((node) => getComputedStyle(node).clipPath), 'inset(50%)')
  assert.equal(await page.locator('.composer-bar').getAttribute('inert'), '')
  assert.ok((await cancel.boundingBox()).height >= 44)
  assert.ok((await stop.boundingBox()).height >= 44)
  await page.waitForFunction(() => {
    const canvas = document.querySelector('.dictation-waveform')
    return canvas?.getContext('2d')?.getImageData(canvas.width - 1, Math.floor(canvas.height / 2), 1, 1).data[3] > 0
  })
  const tallestBar = () => waveform.evaluate((canvas) => {
    const data = canvas.getContext('2d').getImageData(canvas.width - 1, 0, 1, canvas.height).data
    return data.filter((alpha, index) => index % 4 === 3 && alpha > 0).length
  })
  const silence = await tallestBar()
  await emit({ id: randomUUID(), type: 'level', level: 1 })
  await page.waitForTimeout(50)
  assert.equal(await tallestBar(), silence, 'Old recording levels must be ignored')
  for (const level of [.25, .67, .42, .92, .51, .1, 0, .79, .6]) await emit({ id: first, type: 'level', level })
  await page.waitForFunction(() => {
    const canvas = document.querySelector('.dictation-waveform')
    return canvas.getContext('2d').getImageData(canvas.width - 1, Math.floor(canvas.height / 2) - 4, 1, 1).data[3] > 0
  })
  assert.ok(await tallestBar() > silence)
  await page.locator('.composer').screenshot({ path: path.join(shots, 'recording-dark.png') })
  await stop.dblclick()
  await bar.getByText('正在转写…', { exact: true }).waitFor()
  assert.equal(await page.evaluate(() => window.dictationStops.length), 1, 'Only one stop may be requested')
  await emit({ id: first, type: 'result', text: '选中' })
  await waitValue('请看选中部分。')
  assert.equal(await input.evaluate((node) => document.activeElement === node && node.selectionStart === 4), true)
  assert.equal(await page.locator('.attachment').count(), 1)
  assert.equal(await page.evaluate(() => window.sentCommands.length), 0, 'Dictation must not submit a message')

  const pending = await start()
  await stop.click()
  await bar.getByText('正在转写…', { exact: true }).waitFor()
  await page.keyboard.press('Escape')
  await mic.waitFor()
  assert.equal(await page.evaluate((id) => window.dictationCancels.includes(id), pending), true)

  await page.locator('.attachment-remove').click()
  await input.fill('')
  const cancelled = await start()
  await page.waitForFunction(() => document.querySelector('.composer-editor-slot').getBoundingClientRect().height === 0)
  for (const level of [.13, .35, .64, .31, .87, .52, .2, 0, .38, .71, .51]) {
    await emit({ id: cancelled, type: 'level', level })
  }
  await page.waitForFunction(() => {
    const canvas = document.querySelector('.dictation-waveform')
    return canvas.getContext('2d').getImageData(canvas.width - 1, Math.floor(canvas.height / 2) - 4, 1, 1).data[3] > 0
  })
  await page.locator('.composer').screenshot({ path: path.join(shots, 'recording-empty-dark.png') })
  await cancel.click({ position: { x: 3, y: 3 } })
  await mic.waitFor()
  await emit({ id: cancelled, type: 'result', text: '迟到结果' })
  assert.equal(await input.inputValue(), '')
  assert.ok(await input.evaluate((node) => document.activeElement === node))
  await input.fill('请看选中部分。')
  assert.equal(await page.evaluate(() => window.dictationCancels.includes(window.dictationRequests.at(-1).id)), true)

  const permission = await start()
  await emit({ id: permission, type: 'error', error: 'microphone' })
  await status.getByText('请在系统设置中允许 Pi 使用麦克风。', { exact: true }).waitFor()
  await status.getByRole('button', { name: '打开系统设置', exact: true }).click()
  assert.equal(await page.evaluate(() => window.dictationPermission), 'microphone')

  const language = await start()
  await emit({ id: language, type: 'error', error: 'language-unavailable' })
  await status.getByRole('button', { name: '打开听写设置', exact: true }).click()
  assert.equal(await page.evaluate(() => window.dictationPermission), 'language')

  const changed = await start()
  await input.fill('后来输入的内容')
  await stop.click()
  await emit({ id: changed, type: 'result', text: '也要保留。' })
  await waitValue('后来输入的内容也要保留。')

  const previous = await start()
  const expandBeta = page.getByRole('button', { name: '展开 beta 的会话' })
  if (await expandBeta.count()) await expandBeta.click()
  await page.getByText('Beta 的会话', { exact: true }).click()
  await waitValue('')
  await page.waitForFunction((id) => window.dictationCancels.includes(id), previous)
  await emit({ id: previous, type: 'result', text: '上一个会话的结果' })
  assert.equal(await input.inputValue(), '')
  await page.getByText('项目结构', { exact: true }).click()
  await waitValue('后来输入的内容也要保留。')

  await page.evaluate(() => {
    const settings = JSON.parse(sessionStorage.getItem('mock-settings') || '{}')
    sessionStorage.setItem('mock-settings', JSON.stringify({ ...settings, theme: 'light', language: 'en' }))
  })
  await page.setViewportSize({ width: 860, height: 640 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.reload()
  await page.getByRole('button', { name: 'Dictate', exact: true }).click()
  await bar.locator('.dictation-dot').waitFor()
  assert.equal(await bar.getByRole('status').textContent(), 'Microphone on')
  assert.equal(await page.evaluate(() => window.dictationRequests.at(-1).locale), 'en-US')
  assert.ok(await bar.evaluate((node) => parseFloat(getComputedStyle(node).transitionDuration) <= 0.001))
  const box = await page.locator('.composer').boundingBox()
  assert.ok(box.x >= 0 && box.x + box.width <= 860)
  await page.locator('.composer').screenshot({ path: path.join(shots, 'recording-light-reduced-motion.png') })
  const reducedBefore = await tallestBar()
  const id = await page.evaluate(() => window.dictationRequests.at(-1).id)
  await emit({ id, type: 'level', level: 1 })
  await page.waitForTimeout(50)
  assert.equal(await tallestBar(), reducedBefore, 'Reduced motion keeps the waveform static')
  await bar.getByRole('button', { name: 'Cancel dictation' }).click()

  await page.evaluate(() => sessionStorage.setItem('mock-dictation-unavailable', 'true'))
  await page.reload()
  await input.waitFor()
  await page.waitForFunction(() => window.dictationAvailabilityChecked === true)
  assert.equal(await page.locator('.dictation-button').count(), 0, 'Unsupported platforms must not advertise dictation')
  console.log('PASS dictation: live levels, dedicated recording bar, editable draft, attachments, stop and cancellation, permissions, session switching, narrow light theme, reduced motion and unsupported platforms')
}
