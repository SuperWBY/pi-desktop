import { writeFileSync, readFileSync, mkdirSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { CreatorWorkspace } from '../extensions/creator/workspace.ts'
export async function caseCreator({ freshDirs, launch, check }) {
 const dirs = freshDirs('creator'), other = join(dirs.base, 'other-project')
 mkdirSync(other)
 const launcher = resolve('build/pi-seed/1.5.2/pi')
 writeFileSync(join(dirs.userData, 'settings.json'), JSON.stringify({ theme: 'dark', language: 'zh-CN', workspaces: [dirs.base, other], lastWorkspace: dirs.base, sandboxMode: 'disabled', workPanelOpen: true, workPanelTabs: ['home', 'creator'], workPanelTab: 'creator' }))
 const { app, page, errors } = await launch(dirs, 'default', { PI_DESKTOP_PI_PATH: launcher })
 const create = async (kind, name) => {
  const result = await page.evaluate(async ({ kind, name }) => {
   const current = await window.pi.command({ type: 'get_state' })
   return window.pi.creatorAction({ action: 'create', kind, name }, current.data.sessionFile ?? null)
  }, { kind, name })
  if (!result.ok) throw Error(result.error)
 }
 try {
  await page.evaluate(() => { window.__creatorSnapshot = null; window.pi.onRecord(record => { if (record.method === 'creator_state') window.__creatorSnapshot = record.state }) })
  const input = page.locator('.composer-input')
  const before = await page.evaluate(() => window.pi.command({ type: 'get_state' }))
  await input.fill('/create')
  const option = page.getByRole('option', { name: /创意模式/ })
  await option.waitFor({ timeout: 30000 })
  check('菜单说明允许开放创作，内部控制命令隐藏', (await option.innerText()).includes('把想法变成插件') && await page.getByRole('option', { name: /pi-desktop-creator/ }).count() === 0)
  await option.click()
  await page.locator('.creator-mode-bar[data-open="true"]').waitFor()
  check('创意模式成功启用后显示持续状态', await page.getByText('创意模式 · 已开启', { exact: true }).isVisible())
  check('进入创意模式只切换对话，旧工坊和自动侧栏均已移除', await page.locator('.creator-panel').count() === 0 && await page.getByRole('tab', { name: '创意工坊', exact: true }).count() === 0 && await page.locator('.work-panel').isVisible().catch(() => false) === false)
  check('切换不发送模型消息', await input.inputValue() === '' && await page.locator('.message.user').count() === 0)
  await page.getByRole('button', { name: '我的插件', exact: true }).click()
  const panel = page.getByRole('region', { name: '我的插件', exact: true })
  await panel.getByRole('heading', { name: '还没有创建插件', exact: true }).waitFor()
  check('插件市场三类入口明确，空状态引导回到对话创作', await page.getByRole('tab', { name: '我的插件', exact: true }).getAttribute('aria-selected') === 'true' && await page.getByRole('tab', { name: /已安装/ }).count() === 1 && await panel.getByRole('button', { name: '开始创作', exact: true }).isVisible())
  await panel.getByRole('button', { name: '开始创作', exact: true }).click()
  await input.waitFor({ state: 'visible' })
  check('开始创作返回输入区，保留创意模式', await page.locator('.creator-mode-bar[data-open="true"]').isVisible())
  await create('mode', 'mode-library')
  await input.fill('原有未发送内容')
  await page.getByRole('button', { name: '我的插件', exact: true }).click()
  const card = panel.getByRole('article', { name: 'pi-created-mode-library', exact: true })
  await card.waitFor()
  check('自己的真实草稿出现在我的插件，未验证时不提供安装', await card.getByText('草稿', { exact: true }).isVisible() && await card.getByRole('button', { name: '安装并使用', exact: true }).count() === 0)
  await card.getByRole('button', { name: '检查', exact: true }).click()
  await card.getByText('检查通过', { exact: true }).waitFor()
  await card.getByRole('button', { name: '试运行', exact: true }).click()
  await card.getByText('可安装', { exact: true }).waitFor({ timeout: 30000 })
  await card.getByRole('button', { name: '安装并使用', exact: true }).click()
  await page.getByRole('tab', { name: /^已安装/ }).click()
  await page.getByRole('tab', { name: '我的插件', exact: true }).click()
  await card.getByText('已安装', { exact: true }).waitFor({ timeout: 30000 })
  const commands = await page.evaluate(() => window.pi.command({ type: 'get_commands' }))
  check('我的插件可检查、真实加载并一键安装热重载', commands.data.commands.some(command => command.name === 'mode-library'))
  await page.getByRole('tab', { name: /^已安装/ }).click()
  await page.locator('.market-installed').getByText('pi-created-mode-library', { exact: true }).waitFor()
  check('安装后直接切换已安装页可见真实插件', await page.locator('.market-installed').getByText('pi-created-mode-library', { exact: true }).isVisible())
  await page.getByRole('tab', { name: '我的插件', exact: true }).click()
  await card.waitFor()
  const settings = JSON.parse(readFileSync(join(dirs.agent, 'settings.json'), 'utf8'))
  const installedSource = settings.packages.find(source => typeof source === 'string' && source.includes('creator-plugins'))
  check('安装保留独立快照', Boolean(installedSource?.endsWith('/active')))
  await page.waitForFunction(() => document.querySelector('.my-plugins')?.getAttribute('aria-busy') === 'false')
  const removed = await page.evaluate(({ source, cwd }) => window.pi.removePackage(source, cwd), { source: installedSource, cwd: dirs.base })
  check('创作插件可以使用现有包管理卸载', removed.ok, removed.error ?? '')
  await panel.getByRole('button', { name: '刷新我的插件', exact: true }).click()
  await card.getByRole('button', { name: '安装并使用', exact: true }).waitFor()
  const draft = (await page.evaluate(() => window.pi.listCreatedPlugins())).plugins.find(plugin => plugin.kind === 'mode')
  const race = await page.evaluate(async ({ id, cwd }) => {
   const current = await window.pi.command({ type: 'get_state' }), session = current.data.sessionFile
   const security = await window.pi.sessionSecurity(session)
   const installation = window.pi.creatorAction({ action: 'install', id }, session)
   let blocked = false
   try { await window.pi.setSessionPermission({ cwd, sessionPath: session, permission: security?.permission === 'full' ? 'review' : 'full' }) } catch { blocked = true }
   return { blocked, installed: await installation }
  }, { id: draft.id, cwd: dirs.base })
  check('安装期间阻止权限竞态', race.blocked && race.installed.ok)
  await card.getByText('已安装', { exact: true }).waitFor({ timeout: 30000 })
  const extensionPath = join(draft.path, 'extension.ts'), original = readFileSync(extensionPath, 'utf8')
  writeFileSync(extensionPath, original + '\n// revised source\n')
  await panel.getByRole('button', { name: '刷新我的插件', exact: true }).click()
  await card.getByText('草稿', { exact: true }).waitFor()
  check('源码改变立即撤销旧安装资格', await card.getByRole('button', { name: '安装并使用', exact: true }).count() === 0)
  writeFileSync(extensionPath, 'export default function( { invalid')
  const failed = await page.evaluate(async id => {
   const current = await window.pi.command({ type: 'get_state' })
   return window.pi.creatorAction({ action: 'test', id }, current.data.sessionFile)
  }, draft.id)
  check('真实扩展错误不能被handled回执掩盖', !failed.ok && /Failed to load|ParseError/.test(failed.error ?? ''))
  writeFileSync(extensionPath, original + '\n// repaired\n')
  await panel.getByRole('button', { name: '刷新我的插件', exact: true }).click()
  await card.getByRole('button', { name: '检查', exact: true }).click()
  await card.getByRole('button', { name: '试运行', exact: true }).waitFor()
  await card.getByRole('button', { name: '试运行', exact: true }).click()
  await card.getByText('可安装', { exact: true }).waitFor({ timeout: 30000 })
  check('失败后可修复、重新验证和安装', await card.getByRole('button', { name: '安装并使用', exact: true }).isEnabled())
  await create('context', 'context-library'); await create('subagent', 'subagent-library')
  new CreatorWorkspace(other).create('mode', 'other-mode')
  await panel.getByRole('button', { name: '刷新我的插件', exact: true }).click()
  await page.waitForFunction(() => document.querySelectorAll('.my-plugin').length === 4)
  check('我的插件汇总多个项目并显示所属项目', await panel.getByRole('article').count() === 4 && await panel.getByText('所属项目 · other-project', { exact: true }).isVisible())
  await page.getByRole('tab', { name: '我的插件', exact: true }).focus(); await page.keyboard.press('ArrowRight')
  await page.waitForFunction(() => document.querySelector('.market-tabs [role=tab][aria-selected=true]')?.textContent === '发现插件')
  await page.keyboard.press('End')
  await page.waitForFunction(() => document.querySelector('.market-tabs [role=tab][aria-selected=true]')?.textContent === '我的插件')
  check('三页签支持方向键、Home与End', await page.getByRole('tab', { name: '我的插件', exact: true }).getAttribute('aria-selected') === 'true')
  await panel.getByRole('article', { name: 'pi-created-mode-library', exact: true }).getByRole('button', { name: '继续创作', exact: true }).click()
  await input.waitFor({ state: 'visible' })
  await page.waitForFunction(path => document.querySelector('.composer-input')?.value.includes(path), draft.path)
  check('继续创作保留未发送内容并带入实际源码位置', (await input.inputValue()).includes('原有未发送内容') && (await input.inputValue()).includes(draft.path) && await page.locator('.creator-mode-bar[data-open="true"]').isVisible())
  await input.fill('保留的未发送想法')
  await page.getByRole('button', { name: '我的插件', exact: true }).click()
  await panel.getByRole('article', { name: 'pi-created-other-mode', exact: true }).getByRole('button', { name: '继续创作', exact: true }).click()
  await input.waitFor({ state: 'visible' })
  await page.locator('.creator-mode-bar[data-open="true"]').waitFor()
  const switched = await page.evaluate(() => window.pi.command({ type: 'get_state' }))
  check('跨项目继续创作切换到对应真实工作区并开启模式', switched.success && (await input.inputValue()).includes(join(other, '.pi', 'creator')))
  await page.getByRole('button', { name: '退出创意模式', exact: true }).click()
  await page.locator('.creator-mode-bar[data-open="false"]').waitFor()
  await input.fill('/create'); await page.getByRole('option', { name: /创意模式/ }).click()
  await page.locator('.creator-mode-bar[data-open="true"]').waitFor()
  await page.getByRole('button', { name: '我的插件', exact: true }).click()
  await panel.getByRole('article', { name: 'pi-created-other-mode', exact: true }).waitFor()
  check('退出模式不会丢失已创建插件', await panel.getByRole('article').count() === 4)
  const malformed = await page.evaluate(() => window.pi.creatorAction({ action: 'create', kind: 'mode', name: '../../escape' }, null))
  check('非法参数与跨会话请求被拒绝', !malformed.ok)
  const after = await page.evaluate(() => window.pi.command({ type: 'get_state' }))
  check('创建和安装不改变聊天模型', JSON.stringify(before.data.model) === JSON.stringify(after.data.model))
  await page.waitForFunction(() => document.querySelector('.my-plugins')?.getAttribute('aria-busy') === 'false' && document.querySelector('.my-plugins').getAnimations({ subtree: true }).every(animation => animation.playState !== 'running'))
  await page.screenshot({ path: join(dirs.base, '..', '..', 'my-plugins-verified.png') })
  await page.setViewportSize({ width: 900, height: 700 })
  const english = await page.evaluate(() => window.pi.updateSettings({ language: 'en', theme: 'light' }))
  await app.evaluate(({ BrowserWindow }, settings) => BrowserWindow.getAllWindows()[0].webContents.send('app:settings', settings), english)
  await page.getByRole('region', { name: 'My plugins', exact: true }).waitFor()
  check('我的插件支持中英文及窄窗口，无水平溢出', await page.getByRole('tab', { name: 'My plugins', exact: true }).isVisible() && await page.locator('.market-scroll').evaluate(element => element.scrollWidth <= element.clientWidth + 1))
  await page.emulateMedia({ reducedMotion: 'reduce' })
  check('列表与状态动效遵守减少动态效果', await page.locator('.my-plugins').evaluate(element => getComputedStyle(element).animationName === 'none'))
  check('创意模式没有renderer异常', errors.length === 0, errors.join('; '))
 } finally { await app.close() }
}
