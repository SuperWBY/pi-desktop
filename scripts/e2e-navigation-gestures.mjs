import {writeFileSync} from 'node:fs'
import {join} from 'node:path'

export async function caseNavigationGestures({freshDirs,launch,check}) {
 const dirs=freshDirs('navigation-gestures')
 writeFileSync(join(dirs.userData,'settings.json'),JSON.stringify({theme:'dark',language:'zh-CN',workspaces:[dirs.base],lastWorkspace:dirs.base}))
 const {app,page,errors}=await launch(dirs,'default',{PI_DISABLE_NATIVE_SCROLL_PHASE:'1'})
 try {
  await app.evaluate(({ipcMain},cwd)=>{
   const handle=(name,fn)=>{ipcMain.removeHandler(name);ipcMain.handle(name,fn)}
   globalThis.gestureWrites=0
   handle('packages:list',()=>[])
   handle('packages:catalog',()=>({entries:[{name:'gesture-plugin',version:'1.0.0',description:'手势测试插件',publisher:'Fixture',publishedAt:null,npmUrl:'https://www.npmjs.com/package/gesture-plugin',repositoryUrl:null}]}))
   handle('packages:translate',(_,input)=>({ok:true,texts:input.texts}))
   handle('packages:details',()=>({ok:true,details:{name:'gesture-plugin',version:'1.0.0',latestVersion:'1.0.0',versions:['1.0.0'],description:'手势测试插件',author:'Fixture',publisher:'Fixture',license:'MIT',publishedAt:null,homepage:null,repositoryUrl:null,npmUrl:'https://www.npmjs.com/package/gesture-plugin',catalogUrl:'https://pi.dev/packages/gesture-plugin',installSource:'npm:gesture-plugin@1.0.0',unpackedSize:100,dependencies:{},peerDependencies:{},engines:{},manifest:{extensions:['index.ts'],skills:[],themes:[],prompts:[],image:null,video:null},readme:{markdown:'# 手势说明\n\n正文保持固定。\n\n```json\n'+JSON.stringify({long:'a'.repeat(300)})+'\n```',url:'https://example.com/README.md',baseUrl:'https://example.com/',source:'npm-cdn',versionMatched:true},warnings:[],fetchedAt:Date.now()}}))
   handle('packages:install',()=>{globalThis.gestureWrites++;return{ok:true,code:0}})
   handle('skills:list',()=>[{name:'gesture-skill',description:'手势技能',path:cwd+'/skill/SKILL.md',source:'user',symlink:false,requires:{bins:[],missing:[]}}])
   handle('skills:read',()=>({ok:true,content:'# 手势技能\n\n这是手势测试说明。'}))
   handle('connectors:list',()=>[])
   const task={id:'gesture-task',name:'手势任务',prompt:'测试说明',projectPath:cwd,cadence:{type:'daily',time:'09:00'},timezone:'Asia/Shanghai',runMode:'new-session',catchUp:false,catchUpWindowMs:0,notifications:false,enabled:true,createdAt:Date.now(),updatedAt:Date.now(),nextRunAt:Date.now()+86400000,lastRunAt:null,lastStatus:null,consecutiveFailures:0}
   globalThis.gestureTaskDeleted=false
   handle('schedules:list',()=>globalThis.gestureTaskDeleted?[]:[task])
   handle('schedules:delete',()=>{globalThis.gestureTaskDeleted=true;globalThis.gestureWrites++})
   handle('schedules:get',()=>globalThis.gestureTaskDeleted?null:({task,runs:[]}))
   handle('scheduler:background-status',()=>({supported:false,installed:false}))
  },dirs.base)
  await page.evaluate(()=>{window.gesturePhases=[];window.pi.onScrollPhase(value=>window.gesturePhases.push(value))})
  const phase=async type=>{
   const count=await page.evaluate(()=>window.gesturePhases.length)
   await app.evaluate(({BrowserWindow},type)=>BrowserWindow.getAllWindows()[0].webContents.emit('input-event',{}, {type}),type)
   await page.waitForFunction(count=>window.gesturePhases.length>count,count)
  }
  const wheel=async(selector,x,y=0,extra={})=>page.locator(selector).first().evaluate((el,{x,y,extra})=>{const event=new WheelEvent('wheel',{deltaX:x,deltaY:y,bubbles:true,cancelable:true,...extra});el.dispatchEvent(event);return event.defaultPrevented},{x,y,extra})
  const swipe=async(selector,x)=>{await phase('gestureScrollBegin');for(let i=0;i<4;i++)await wheel(selector,x/4);await phase('gestureScrollEnd')}
  await page.locator('.plugins-page-entry').click()
  await page.locator('#market-gesture-plugin').waitFor()
  await page.locator('#market-gesture-plugin').click()
  await page.locator('.market-readme pre').waitFor()
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.market-content')).opacity==='1')
  const race=await page.evaluate(async()=>{
    const original=window.setTimeout,source=document.querySelector('.market-description');let intercepted=false
    try {
      return await new Promise(resolve=>{
        window.setTimeout=function(handler,delay,...args){
          if(delay===120&&!intercepted&&typeof handler==='function'){
            intercepted=true
            return original.call(window,()=>{
              handler(...args)
              source.dispatchEvent(new WheelEvent('wheel',{deltaX:-20,bubbles:true,cancelable:true}))
              requestAnimationFrame(()=>requestAnimationFrame(()=>{
                const element=document.querySelector('.navigation-gesture')
                resolve({visible:!!element,progress:element?+element.style.getPropertyValue('--gesture-progress'):0})
              }))
            },300)
          }
          return original.call(window,handler,delay,...args)
        }
        source.dispatchEvent(new WheelEvent('wheel',{deltaX:-20,bubbles:true,cancelable:true}))
      })
    } finally {window.setTimeout=original;source.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))}
  })
  check('回弹收起与下一次手势交叠时提示仍及时出现',race.visible&&race.progress>0,JSON.stringify(race))
  await page.locator('.navigation-gesture').waitFor({state:'detached'})
  await page.waitForTimeout(260) // Separate fallback wheel sequences from the previous gesture's inertia.
  await page.evaluate(()=>{
   window.gestureFallbackMs=null;window.gestureLastWheel=null
   const observer=new MutationObserver(()=>{if(document.querySelector('#market-gesture-plugin')&&window.gestureLastWheel!==null){window.gestureFallbackMs=performance.now()-window.gestureLastWheel;observer.disconnect()}})
   observer.observe(document.querySelector('.market-scroll'),{childList:true,subtree:true})
  })
  for(let i=0;i<4;i++){
   await page.evaluate(()=>{window.gestureLastWheel=performance.now()})
   await wheel('.market-description',-35)
  }
  await page.locator('#market-gesture-plugin').waitFor()
  check('无原生阶段事件时仍可在滚动结束后返回',await page.locator('#market-gesture-plugin').isVisible())
  const fallbackMs=await page.evaluate(()=>window.gestureFallbackMs)
  check('无原生松手信号时缩短停止滚动后的等待',fallbackMs!==null&&fallbackMs<100,JSON.stringify({fallbackMs}))
  await page.keyboard.press('Meta+]')
  await page.locator('.market-info').waitFor()
  await page.waitForFunction(()=>getComputedStyle(document.querySelector('.market-content')).opacity==='1')
  check('Mac前进快捷键与手势共用同一浏览历史',await page.locator('.market-info').count()===1)
  await phase('gestureScrollBegin')
  await wheel('.market-description',-16)
  await page.locator('.navigation-gesture').waitFor()
  const tracking=await page.evaluate(async()=>{
    const element=document.querySelector('.navigation-gesture'),source=document.querySelector('.market-description')
    let paints=0,frames=0,running=true;const gaps=[];let previous=performance.now()
    const observer=new MutationObserver(records=>{paints+=records.filter(record=>record.attributeName==='style').length})
    observer.observe(element,{attributes:true,attributeFilter:['style']})
    const frame=time=>{if(!running)return;frames++;gaps.push(time-previous);previous=time;requestAnimationFrame(frame)};requestAnimationFrame(frame)
    for(let i=0;i<40;i++){source.dispatchEvent(new WheelEvent('wheel',{deltaX:-.25,bubbles:true,cancelable:true}));await new Promise(resolve=>setTimeout(resolve,2))}
    await new Promise(resolve=>requestAnimationFrame(()=>requestAnimationFrame(resolve)))
    running=false;observer.disconnect();gaps.sort((a,b)=>a-b)
    return{paints,frames,p95FrameMs:gaps[Math.floor(gaps.length*.95)],width:element.getBoundingClientRect().width}
  })
  check('连续滑动每帧最多更新一次，提示板块更短',tracking.paints<=tracking.frames+2&&tracking.width<=36,JSON.stringify(tracking))
  await phase('gestureScrollEnd');await page.locator('.navigation-gesture').waitFor({state:'detached'})
  const before=await page.locator('.market-content').boundingBox()
  await phase('gestureScrollBegin')
  await wheel('.market-description',-30)
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)))
  const shallow=await page.locator('.navigation-gesture').evaluate(el=>({opacity:+getComputedStyle(el).opacity,transform:getComputedStyle(el).transform,progress:+el.style.getPropertyValue('--gesture-progress'),background:getComputedStyle(el).backgroundColor}))
  await page.screenshot({path:join(dirs.base,'gesture-shallow.png')})
  await wheel('.market-description',-45)
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)))
  const deeper=await page.locator('.navigation-gesture').evaluate(el=>({opacity:+getComputedStyle(el).opacity,transform:getComputedStyle(el).transform,progress:+el.style.getPropertyValue('--gesture-progress')}))
  const during=await page.locator('.market-content').boundingBox()
  check('手势板块独立覆盖，随距离连续拉出并由浅入深，正文位置不变',deeper.progress>shallow.progress&&deeper.opacity>shallow.opacity&&deeper.transform!==shallow.transform&&shallow.background!=='rgba(0, 0, 0, 0)'&&Math.abs(during.x-before.x)<.5&&Math.abs(during.width-before.width)<.5,JSON.stringify({shallow,deeper,before,during}))
  await page.screenshot({path:join(dirs.base,'gesture-deeper.png')})
  await wheel('.market-description',60)
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)))
  const reversed=await page.locator('.navigation-gesture').evaluate(el=>+el.style.getPropertyValue('--gesture-progress'))
  check('回拉时提示板块同步变浅并缩回',reversed<shallow.progress)
  await phase('gestureScrollEnd')
  await page.locator('.navigation-gesture').waitFor({state:'detached'})
  check('不足阈值松手回弹，不退出详情',await page.locator('.market-info').count()===1)
  await phase('gestureScrollBegin')
  for(let i=0;i<4;i++)await wheel('.market-description',-35)
  await page.waitForTimeout(300)
  check('达到阈值后手指停住仍不切页，等待原生松手事件',await page.locator('.market-info').count()===1&&await page.locator('.navigation-gesture[data-ready="true"]').count()===1)
  await page.evaluate(()=>{
    window.gestureCommitMs=null
    const off=window.pi.onScrollPhase(phase=>{if(phase!=='end')return;off();const start=performance.now();const observer=new MutationObserver(()=>{if(document.querySelector('#market-gesture-plugin')){window.gestureCommitMs=performance.now()-start;observer.disconnect()}});observer.observe(document.querySelector('.market-scroll'),{childList:true,subtree:true})})
  })
  await phase('gestureScrollEnd')
  await page.locator('#market-gesture-plugin').waitFor()
  const releaseMs=await page.evaluate(()=>window.gestureCommitMs)
  check('原生松手后立即切页，没有额外退场等待',releaseMs!==null&&releaseMs<100,JSON.stringify({releaseMs}))
  for(let i=0;i<5;i++)await wheel('.market-section-heading',-35)
  await page.waitForTimeout(240)
  check('一次松手只返回一层，惯性不会继续关闭市场',await page.locator('#market-gesture-plugin').isVisible())
  await swipe('.market-section-heading',140)
  await page.locator('.market-info').waitFor()
  check('反向轻扫可重新前进到刚才的插件详情',await page.locator('.market-info').count()===1)
  await phase('gestureScrollBegin')
  for(let i=0;i<4;i++)await wheel('.market-readme pre',-40)
  await phase('gestureScrollEnd')
  check('代码块横向滚动不触发页面导航',await page.locator('.market-info').count()===1&&await page.locator('.navigation-gesture:not([data-releasing="true"])').count()===0)
  for(const extra of [{ctrlKey:true},{shiftKey:true}]){
   await phase('gestureScrollBegin');const prevented=await wheel('.market-description',-150,0,extra);await phase('gestureScrollEnd')
   check(extra.ctrlKey?'捏合缩放不被翻页手势截获':'Shift横向滚动不被截获',!prevented&&await page.locator('.market-info').count()===1)
  }
  await phase('gestureScrollBegin');await wheel('.market-description',1,100);await wheel('.market-description',-150);await phase('gestureScrollEnd')
  check('纵向滚动锁定后不会因斜向抖动翻页',await page.locator('.market-info').count()===1)
  await page.getByRole('button',{name:'所有插件',exact:true}).click()
  await page.locator('#market-gesture-plugin').waitFor()
  await page.getByRole('button',{name:'从链接安装',exact:true}).click()
  await swipe('.market-section-heading',-150)
  check('安装弹窗打开时不导航且不执行包写入',await page.getByRole('dialog',{name:'从链接安装',exact:true}).isVisible()&&await app.evaluate(()=>globalThis.gestureWrites===0))
  await page.keyboard.press('Escape');await page.locator('.modal-overlay').waitFor({state:'detached'})
  await phase('gestureScrollBegin');const inputPrevented=await wheel('.market-search input',-160);await phase('gestureScrollEnd')
  check('输入框上的手势不截获文本操作',!inputPrevented&&await page.locator('#market-gesture-plugin').count()===1)
  await page.locator('.skills-page-entry').click()
  await page.locator('.skill-card').first().click()
  await page.locator('.skill-readme').waitFor()
  await swipe('.skill-readme',-140)
  await page.locator('.skill-card').waitFor()
  await swipe('.skills-scroll',140)
  await page.locator('.skill-readme').waitFor()
  check('技能详情支持手势返回和前进',await page.locator('.skill-readme').isVisible())
  await page.locator('.schedules-entry').click()
  await page.locator('.schedule-row').first().click()
  await page.locator('.schedule-detail').waitFor()
  await swipe('.schedule-detail',-140)
  await page.locator('.schedule-row').waitFor()
  await swipe('.skills-scroll',140)
  await page.locator('.schedule-detail').waitFor()
  check('定时任务详情支持返回和前进，手势不会运行或编辑任务',await page.locator('.schedule-detail').isVisible())
  await page.locator('.schedule-detail').getByRole('button',{name:'删除',exact:true}).click()
  await page.locator('.modal').getByRole('button',{name:'删除',exact:true}).click()
  await page.locator('.schedule-detail').waitFor({state:'detached'})
  await swipe('.skills-empty',140)
  check('删除任务后不会前进到失效详情',await page.locator('.schedule-detail').count()===0)
  await swipe('.skills-empty',-140)
  await page.locator('.skill-card').first().waitFor()
  check('失效历史不会锁死全局导航，仍可返回上一个一级页面',await page.locator('.skill-card').count()===1&&await app.evaluate(()=>globalThis.gestureWrites===1))
  await swipe('.skills-scroll',140)
  await page.locator('.schedules-entry[aria-current="page"]').waitFor()
  check('一级页面之间也可以向前恢复刚才的页面',await page.locator('.schedule-detail').count()===0)
  await page.keyboard.press('Meta+,')
  await page.locator('.settings-nav-item').filter({hasText:'模型'}).click()
  await page.locator('.settings-nav-item').filter({hasText:'常规'}).click()
  await swipe('.settings-page-title',-140)
  await page.getByRole('heading',{name:'模型',exact:true}).waitFor()
  check('设置分类普通点击保留访问历史，返回到刚才的模型页',await page.locator('.settings-page').isVisible())
  await swipe('.settings-page-title',140)
  await page.getByRole('heading',{name:'常规',exact:true}).waitFor()
  check('设置分类支持向前轻扫',true)
  await page.emulateMedia({reducedMotion:'reduce'})
  await phase('gestureScrollBegin');await wheel('.settings-page-title',-60)
  await page.evaluate(()=>new Promise(resolve=>requestAnimationFrame(resolve)))
  const reduced=await page.locator('.navigation-gesture').evaluate(el=>({transform:getComputedStyle(el).transform,transition:getComputedStyle(el).transitionDuration}))
  check('减少动态效果时保留手势提示并停止位移',reduced.transform==='none'&&reduced.transition==='0s',JSON.stringify(reduced))
  await phase('gestureScrollEnd')
  await swipe('.settings-page-title',-140)
  await page.getByRole('heading',{name:'模型',exact:true}).waitFor()
  check('减少动态效果仍可完成导航',true)
  await page.locator('.settings-nav-item').filter({hasText:'键盘快捷键'}).click()
  await page.getByText('双指左右轻扫',{exact:true}).waitFor()
  const englishSettings=await page.evaluate(()=>window.pi.updateSettings({language:'en'}))
  await app.evaluate(({BrowserWindow},settings)=>BrowserWindow.getAllWindows()[0].webContents.send('app:settings',settings),englishSettings)
  await page.getByText('Trackpad gestures',{exact:true}).waitFor()
  check('设置中提供中英文手势说明和返回前进快捷键',await page.getByText('Swipe left or right with two fingers',{exact:true}).isVisible())
  check('手势过程中没有renderer异常',errors.length===0,errors.join('; '))
 } finally {await app.close()}
}
