// Real Electron views and local fixture. Only model/tool progress is simulated.
import assert from 'node:assert/strict'
import { _electron as electron } from 'playwright'
import { createServer } from 'node:http'
import { mkdtemp, mkdir, writeFile, readdir, readFile, rm } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'
const root = resolve(import.meta.dirname, '..')
const temp = await mkdtemp(join(tmpdir(), 'pi-cu-preview-'))
const data = join(temp, 'userData')
const server = createServer((_req, res) => { res.setHeader('content-type','text/html'); res.end('<meta name="viewport" content="width=device-width, initial-scale=1"><title>Orders</title><button onclick="document.querySelector(\'p\').textContent=\'Found 42\'">Query</button><p>Pending</p>') })
await new Promise(ok => server.listen(0, '127.0.0.1', ok))
let app, editor
try {
  await mkdir(data)
  await writeFile(join(data,'settings.json'), JSON.stringify({lastWorkspace:temp,workspaces:[temp]}))
  app = await electron.launch({cwd:root,executablePath:process.env.PI_PREVIEW_APP, args:[...(process.env.PI_PREVIEW_APP ? [] : ['.']), '--user-data-dir='+data],env:{...process.env,HOME:temp,PI_DESKTOP_PI_PATH:join(root,'scripts/mock-pi.mjs'),PI_CODING_AGENT_DIR:join(temp,'agent'),PI_CODING_AGENT_SESSION_DIR:join(temp,'sessions')}})
  const page = await app.firstWindow()
  await page.waitForSelector('.status-dot.is-ready')
  await page.waitForSelector('.composer-input')
  const shots = process.env.PI_PREVIEW_OUTPUT
  if (shots) {
    await mkdir(shots,{recursive:true})
    await page.locator('.approval-mode-chip').click()
    await page.screenshot({animations:'disabled',path:join(shots,'new-chat.png')})
    await page.keyboard.press('Escape')
  }
  await writeFile(join(temp,'sample-note.md'),'Example project note')
  await page.getByRole('button',{name:'工作面板',exact:true}).click()
  const homeSearch = page.locator('.work-home-search input')
  await homeSearch.waitFor()
  if (shots) await page.screenshot({animations:'disabled',path:join(shots,'work-home.png')})
  await homeSearch.fill('sample-note')
  await page.locator('.work-home-results button').filter({hasText:'sample-note.md'}).click()
  await page.getByText('Example project note',{exact:true}).waitFor()
  await page.getByRole('button',{name:'新标签页',exact:true}).click()
  await homeSearch.fill('http://127.0.0.1:'+server.address().port+'/manual')
  await homeSearch.press('Enter')
  await page.locator('.browser-address input').waitFor()
  await page.waitForFunction(expected=>document.querySelector('.browser-address input').value===expected,'http://127.0.0.1:'+server.address().port+'/manual')
  await page.getByRole('button',{name:'工作面板',exact:true}).click()
  const dir = join(data,'computer-use-bridges')
  const bridge = JSON.parse(await readFile(join(dir,(await readdir(dir))[0]),'utf8'))
  const post = async (path,body,owner='fixture',tab='main') => (await fetch('http://127.0.0.1:'+bridge.port+path,{method:'POST',headers:{authorization:'Bearer '+bridge.token,'x-pi-controller':owner,'x-pi-page':tab,'x-pi-pid':String(process.pid)},body:JSON.stringify(body)})).json()
  assert.ok((await post('/claim',{})).ok)
  assert.equal((await post('/claim',{},'other')).ok,false)
  const url = 'http://127.0.0.1:'+server.address().port
  await page.locator('.composer-input').fill('my draft')
  const send = record => app.evaluate(({BrowserWindow},r)=> BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('index.html')).webContents.send('pi:record',r),record)
  await send({type:'agent_start'})
  await send({type:'tool_execution_start',toolCallId:'obs',toolName:'computer_use_session_observe'})
  assert.ok((await post('/navigate',{url})).ok)
  let obs
  for(let i=0;i<50;i++){obs=await post('/observe',{});if(obs.candidates?.length)break;await page.waitForTimeout(100)}
  assert.equal(obs.candidates[0].name,'Query')
  await send({type:'tool_execution_end',toolCallId:'obs',toolName:'computer_use_session_observe',result:{details:{backend:'inapp',documentId:obs.documentId,url:obs.state.url,title:'Orders'}}})
  const card = page.locator('.cu-preview')
  await card.locator('img').waitFor()
  await send({type:'tool_execution_start',toolCallId:'act',toolName:'computer_use_session_act',args:{type:'click',candidateId:obs.candidates[0].id}})
  await card.locator('.cu-pointer').waitFor()
  // A separate desktop process owns the foreground and receives the user's typing.
  const editorScript = join(temp, 'editor.cjs')
  await writeFile(editorScript, `const {app,BrowserWindow}=require('electron');let w;app.whenReady().then(()=>{w=new BrowserWindow({width:320,height:180});w.loadURL('data:text/html,<textarea autofocus></textarea>');w.show();w.focus()})`)
  editor = await electron.launch({args:[editorScript,'--user-data-dir='+join(temp,'editor-data')],env:{...process.env,HOME:temp}})
  const front = await editor.firstWindow()
  await front.locator('textarea').click()
  await front.keyboard.type('outside')
  const desktopState = () => editor.evaluate(({BrowserWindow,screen}) => ({focused:BrowserWindow.getAllWindows()[0].isFocused(),point:screen.getCursorScreenPoint()}))
  const beforeClick = await desktopState()
  assert.ok(beforeClick.focused)
  const acted = await post('/act',{type:'click',candidateId:obs.candidates[0].id,snapshotId:obs.snapshotId,expectedUrl:obs.state.url})
  assert.ok(acted.ok,JSON.stringify(acted))
  assert.deepEqual(await desktopState(),beforeClick,'background click must leave system cursor and foreground window unchanged')
  await front.keyboard.type(' intact')
  assert.equal(await front.locator('textarea').inputValue(),'outside intact')
  assert.equal(await page.locator('.composer-input').inputValue(),'my draft')
  const after=await post('/observe',{})
  assert.match((await post('/read-text',{snapshotId:after.snapshotId,expectedUrl:after.state.url})).text,/Found 42/)
  const other = (path,body) => post(path,body,'fixture','comparison')
  assert.equal((await other('/viewport',{width:0,height:800})).ok,false)
  assert.ok((await other('/viewport',{width:390,height:844})).ok)
  assert.ok((await other('/navigate',{url:url+'/second'})).ok)
  let second
  for(let i=0;i<50;i++){second=await other('/observe',{});if(second.candidates?.length)break;await page.waitForTimeout(75)}
  assert.notEqual(second.documentId,obs.documentId)
  const stale=await other('/act',{type:'click',candidateId:after.candidates[0].id,snapshotId:after.snapshotId,expectedUrl:after.state.url})
  assert.equal(stale.ok,false,'wrong page must reject an action')
  await send({type:'tool_execution_start',toolCallId:'obs2',toolName:'computer_use_session_observe'})
  await send({type:'tool_execution_end',toolCallId:'obs2',toolName:'computer_use_session_observe',result:{details:{backend:'inapp',page:'comparison',documentId:second.documentId,url:second.state.url,title:'Comparison'}}})
  await card.locator('.cu-back-page img').first().waitFor()
  assert.equal(await page.locator('.project-tree').count(), 1, 'project aliases should have one sidebar row')
  assert.equal(await card.locator('select').count(), 0)
  assert.equal(await card.getByText('2/2').count(), 0)
  const box=await card.boundingBox(), main=await page.locator('main.main').boundingBox()
  assert.ok(main.x+main.width-box.x-box.width<25 && box.y-main.y<105,'preview anchors top right')
  assert.equal(await card.getByText('电脑操作',{exact:true}).count(),0)
  const phone = app.evaluate(({webContents},pageUrl) => {
    const target = webContents.getAllWebContents().find(w=>w.getURL()===pageUrl)
    return target.executeJavaScript('[innerWidth,innerHeight,matchMedia("(max-width: 400px)").matches]')
  },url+'/second')
  assert.deepEqual(await phone,[390,844,true])
  assert.deepEqual(second.viewport,{width:390,height:844})
  await page.waitForFunction(()=>{const r=document.querySelector('.cu-surface')?.getBoundingClientRect();return r && r.height/r.width>2})
  const original=await card.boundingBox()
  await page.mouse.move(original.x+original.width/2,original.y+original.height/2)
  await page.mouse.down()
  await page.mouse.move(original.x+original.width/2-120,original.y+original.height/2+95,{steps:8})
  await page.mouse.up()
  const moved=await card.boundingBox()
  assert.ok(moved.x<original.x-100 && moved.y>original.y+80,'drag repositions portrait preview')
  await card.getByRole('button',{name:'恢复右上角位置'}).click()
  await card.locator('.cu-surface').click()
  const follow=page.locator('.browser-follow button')
  await follow.waitFor()
  assert.equal(await follow.getAttribute('aria-pressed'),'true')
  await card.waitFor({state:'hidden'})
  assert.equal(await page.locator('.browser-address input').inputValue(),url+'/second')
  assert.deepEqual(await app.evaluate(({webContents},pageUrl)=>webContents.getAllWebContents().find(w=>w.getURL()===pageUrl).executeJavaScript('[innerWidth,innerHeight]'),url+'/second'),[390,844])
  await follow.click()
  await card.waitFor()
  await send({type:'tool_execution_start',toolCallId:'again',toolName:'computer_use_session_observe'})
  await send({type:'tool_execution_end',toolCallId:'again',toolName:'computer_use_session_observe',result:{details:{backend:'inapp',documentId:obs.documentId,url:obs.state.url,title:'Orders'}}})
  assert.equal(await page.locator('.browser-address input').inputValue(),url+'/second')
  await follow.click()
  await page.waitForFunction(expected=>document.querySelector('.browser-address input').value===expected,url+'/')
  await page.locator('.work-head').getByRole('button',{name:'关闭',exact:true}).click()
  await send({type:'tool_execution_start',toolCallId:'phone-again',toolName:'computer_use_session_observe'})
  await send({type:'tool_execution_end',toolCallId:'phone-again',toolName:'computer_use_session_observe',result:{details:{backend:'inapp',page:'comparison',documentId:second.documentId,url:second.state.url,title:'Comparison'}}})
  await card.locator('.cu-back-page').first().click({position:{x:4,y:18}})
  await card.locator('.cu-picture:not([hidden]) img[alt="Orders"]').waitFor()
  await card.locator('.cu-summary').focus()
  await page.keyboard.press('ArrowRight')
  await card.locator('.cu-picture:not([hidden]) img[alt="Comparison"]').waitFor()
  await card.locator('.cu-back-page').first().click({position:{x:3,y:14}})
  await card.locator('.cu-picture:not([hidden]) img[alt="Orders"]').waitFor()
  await app.evaluate(({BrowserWindow}) => {
    const win = BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('index.html'))
    win.setMinimumSize(510,500)
    win.setSize(510,680)
  })
  await page.waitForFunction(() => {
    const card = document.querySelector('.cu-preview')?.getBoundingClientRect()
    const transcript = document.querySelector('.conversation-region > .chat-scroll, .conversation-region > .chat-wrap')?.getBoundingClientRect()
    return card && transcript && card.bottom <= transcript.top + 1
  },undefined,{timeout:5000})
  await post('/navigate',{url:url+'/another'})
  await card.locator('.cu-picture:not([hidden]) img').waitFor({state:'hidden'})
  await send({type:'agent_settled'})
  await card.locator('.cu-summary[aria-expanded="false"]').waitFor()
  if (process.env.PI_PREVIEW_SCREENSHOT) await page.screenshot({path:process.env.PI_PREVIEW_SCREENSHOT})
  await post('/release',{})
  assert.ok((await post('/claim',{},'other')).ok)
  console.log('PASS hidden target, actual frame and Pi pointer, guarded click, focused editor retains input, result readback, navigation invalidation, task ownership and collapse')
} finally {
  await editor?.close()
  await app?.close()
  server.close()
  await rm(temp,{recursive:true,force:true,maxRetries:8,retryDelay:100})
}
