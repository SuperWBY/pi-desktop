const conversations=createViewHistory({id:'a'},'a')
conversations.record({id:'draft'},'draft')
conversations.record({id:'saved'},'saved',false,true)
assert.equal(conversations.move('back').id,'a','promoting a draft must not create a duplicate history entry')
conversations.cancelRestore()
assert.equal(conversations.currentKey(),'saved','failed navigation restores the previous history position')
assert.equal(conversations.canGo('back'),true,'failed navigation must not lock history')
console.log('✓ Draft promotion and failed navigation preserve usable conversation history')
