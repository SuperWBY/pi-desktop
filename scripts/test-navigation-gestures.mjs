import assert from 'node:assert/strict'
import {createViewHistory,TrackpadSwipe,SWIPE_DISTANCE} from '../src/renderer/src/lib/navigation-gestures.ts'
const history=createViewHistory({id:0},'list')
history.record({id:1},'detail')
assert.equal(history.canGo('back'),true)
assert.deepEqual(history.move('back'),{id:0});history.record({id:0},'list')
assert.deepEqual(history.move('forward'),{id:1});history.record({id:1},'detail')
history.record({id:2},'detail')
assert.deepEqual(history.move('back'),{id:0});history.record({id:0},'list')
assert.deepEqual(history.move('forward'),{id:2});history.record({id:2},'detail')
history.record({id:0},'list',true) // Existing back buttons retain the forward destination.
assert.equal(history.canGo('forward'),true)
history.record({id:3},'another')
assert.equal(history.canGo('forward'),false)
assert.equal(history.move('forward'),undefined)
const swipe=new TrackpadSwipe()
const move=(x,y=0,time=10,extra={})=>swipe.move({x,y,time,...extra})
assert.equal(move(-8),null)
assert.equal(move(-24,0,20).direction,'back')
assert.equal(swipe.release(),null,'short drag cancels')
swipe.start(true)
const deep=move(-60);const reversed=move(50,0,20);assert.ok(deep.progress>reversed.progress&&deep.progress<1)
assert.equal(swipe.release(),null,'reversing drag cancels before threshold')
swipe.start(true)
move(-70);move(-70,0,20)
assert.equal(swipe.release(),'back')
assert.equal(move(-200,0,500),null,'native momentum never starts another navigation')
assert.equal(swipe.release(),null)
swipe.start(true);move(130);assert.equal(swipe.release(),'forward')
swipe.start();move(130);assert.equal(swipe.release(),'forward')
move(130,0,500);assert.equal(swipe.release(),'forward','a new separated gesture is independent')
for(const extra of [{modified:true},{blocked:true},{mode:1}]){
 swipe.start();assert.equal(move(-160,0,10,extra),null);assert.equal(swipe.release(),null)
}
swipe.start();move(1,30);assert.equal(move(-200,0,20),null);assert.equal(swipe.release(),null,'vertical gesture stays scrolling')
swipe.start();move(-150);swipe.cancel();assert.equal(swipe.release(),null)
console.log('✓ Navigation history, forward restoration, branching, proportional drag, threshold/cancellation, axis lock, modifier exclusion and native momentum')

